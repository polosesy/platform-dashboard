import type { Request, Response, Router } from "express";
import type { Env } from "../env.js";
import type { DiagramSpec, LiveDiagramSnapshot, NsgRuleEntry } from "@aud/types";
import {
  saveDiagramSpec,
  getDiagramSpec,
  listDiagramSpecs,
  buildLiveSnapshot,
} from "../services/liveAggregator.js";
import { mockDiagramSpec, generateMockSnapshot } from "../services/liveDiagramMock.js";
import { tryGetArchitectureGraphFromAzure, clearGraphCache } from "../services/azure.js";
import { generateDiagramSpec } from "../services/specGenerator.js";
import { fetchEdgeNetworkDetail, fetchNsgInfo, fetchBackendPoolInfo, fetchAksPlaneDetail, fetchVmssInstances } from "../services/edgeDetailService.js";
import { debug } from "../infra/logger.js";
import {
  assertAllowedSubscription,
  assertArmResourceId,
  parseSubscriptionIds,
  queryArmResourceId,
  queryString,
  sendError,
} from "../infra/requestParams.js";

// Seed the mock diagram on startup
saveDiagramSpec(mockDiagramSpec);

const DEFAULT_DIAGRAM_ID = "prod-infra";

export function registerLiveDiagramRoutes(router: Router, env: Env) {
  /**
   * Snapshot for a diagram: live data when Azure integration is enabled (or the
   * diagram was auto-generated from Azure), otherwise / on failure the mock snapshot.
   */
  async function resolveSnapshot(bearerToken: string | undefined, diagramId: string) {
    const isAutoGenerated = diagramId.startsWith("auto-");
    if (!env.AZURE_LIVE_DIAGRAM_ENABLED && !isAutoGenerated) {
      return withSource(generateMockSnapshot(), "mock");
    }
    try {
      const snapshot = await buildLiveSnapshot(env, bearerToken, diagramId);
      if (snapshot && hasRealData(snapshot)) return snapshot;
      // Auto-generated diagrams carry simulated traffic even without resolved metrics
      if (snapshot && isAutoGenerated) return withSource(snapshot, "mock");
      return withSource(generateMockSnapshot(), "mock");
    } catch (err: unknown) {
      return withSource(generateMockSnapshot(), "mock", err instanceof Error ? err.message : "Unknown error");
    }
  }

  // ── List all diagrams ──
  router.get("/api/live/diagrams", (_req: Request, res: Response) => {
    res.json({ diagrams: listDiagramSpecs() });
  });

  // ── Get a single diagram spec ──
  router.get("/api/live/diagrams/:id", (req: Request, res: Response) => {
    const spec = getDiagramSpec(req.params.id ?? "");
    if (!spec) {
      res.status(404).json({ error: "Diagram not found" });
      return;
    }
    res.json({ diagram: spec });
  });

  // ── Auto-generate diagram from Azure Resource Graph ──
  // IMPORTANT: Register before generic POST /api/live/diagrams to avoid route conflicts
  router.post("/api/live/diagrams/generate", async (req: Request, res: Response) => {
    try {
      const subscriptionId = assertAllowedSubscription(
        env,
        typeof req.body?.subscriptionId === "string" ? req.body.subscriptionId : undefined,
      );

      // Always bypass the graph cache on generate to ensure fresh Azure data
      clearGraphCache();
      const graph = await tryGetArchitectureGraphFromAzure(env, req.auth?.bearerToken, { subscriptionId });

      if (!graph) {
        // Azure Resource Graph not available — fall back to mock diagram with demo traffic
        const spec: DiagramSpec = { ...mockDiagramSpec, id: "auto-demo", name: "Demo Infrastructure", updatedAt: new Date().toISOString() };
        saveDiagramSpec(spec);
        res.status(201).json({ ok: true, diagram: spec, _source: "mock" });
        return;
      }

      const subId = subscriptionId ?? parseSubscriptionIds(env)[0] ?? "default";
      const { spec, containmentDiagnostics } = await generateDiagramSpec(graph, subId);
      saveDiagramSpec(spec);
      debug("[live-diagram] generated spec", spec.id, {
        graphNodes: graph.nodes.length,
        graphEdges: graph.edges.length,
        specNodes: spec.nodes.length,
        specEdges: spec.edges.length,
        containment: containmentDiagnostics,
      });

      res.status(201).json({
        ok: true,
        diagram: spec,
        _source: "azure",
        _diagnostics: {
          graphNodes: graph.nodes.length,
          graphEdges: graph.edges.length,
          specNodes: spec.nodes.length,
          specEdges: spec.edges.length,
        },
      });
    } catch (e: unknown) {
      sendError(res, e, "diagram_generate_failed", "live-diagram");
    }
  });

  // ── Save/update a diagram spec ──
  router.post("/api/live/diagrams", (req: Request, res: Response) => {
    const body = req.body as DiagramSpec | undefined;
    if (!body?.id || !body?.version || !Array.isArray(body.nodes) || !Array.isArray(body.edges)) {
      res.status(400).json({ error: "Invalid diagram spec: id, version, nodes[] and edges[] required" });
      return;
    }
    body.updatedAt = new Date().toISOString();
    if (!body.createdAt) body.createdAt = body.updatedAt;
    saveDiagramSpec(body);
    res.status(201).json({ ok: true, id: body.id });
  });

  // ── Live snapshot (REST polling) ──
  router.get("/api/live/snapshot", async (req: Request, res: Response) => {
    const diagramId = queryString(req, "diagramId") ?? DEFAULT_DIAGRAM_ID;
    const snapshot = await resolveSnapshot(req.auth?.bearerToken, diagramId);
    if (!res.writableEnded) res.json(snapshot);
  });

  // ── SSE stream (server-push) ──
  // NOTE: EventSource cannot send an Authorization header, so this stream runs
  // without the user's token (SP fallback / mock). Polling mode carries the token.
  router.get("/api/live/stream", (req: Request, res: Response) => {
    const diagramId = queryString(req, "diagramId") ?? DEFAULT_DIAGRAM_ID;
    const spec = getDiagramSpec(diagramId);
    const intervalSec = Math.max(5, spec?.settings.refreshIntervalSec ?? 30);

    res.writeHead(200, {
      "Content-Type": "text/event-stream",
      "Cache-Control": "no-cache",
      Connection: "keep-alive",
      "X-Accel-Buffering": "no",
    });

    let closed = false;
    let inFlight = false;

    const write = (chunk: string) => {
      if (closed || res.writableEnded) return;
      try {
        res.write(chunk);
      } catch {
        closed = true;
      }
    };

    const sendSnapshot = async () => {
      // Skip a tick rather than piling up overlapping Azure fan-outs when a build is slow
      if (closed || inFlight) return;
      inFlight = true;
      try {
        const data = await resolveSnapshot(req.auth?.bearerToken, diagramId);
        write(`data: ${JSON.stringify(data)}\n\n`);
      } finally {
        inFlight = false;
      }
    };

    void sendSnapshot();
    const timer = setInterval(() => void sendSnapshot(), intervalSec * 1000);
    // Comment line keeps idle proxies from dropping the connection
    const heartbeat = setInterval(() => write(": ping\n\n"), 15_000);

    req.on("close", () => {
      closed = true;
      clearInterval(timer);
      clearInterval(heartbeat);
    });
  });

  // ── Edge Network Detail (on-demand, 30s cached) ──
  router.get("/api/live/edge-detail", async (req: Request, res: Response) => {
    const diagramId = queryString(req, "diagramId") ?? DEFAULT_DIAGRAM_ID;
    const edgeId = queryString(req, "edgeId");
    if (!edgeId) return void res.status(400).json({ error: "edgeId_required" });

    try {
      res.json(await fetchEdgeNetworkDetail(env, req.auth?.bearerToken, diagramId, edgeId));
    } catch (e: unknown) {
      sendError(res, e, "edge_detail_error", "live-diagram");
    }
  });

  // ── NSG Detail (on-demand, fetch security rules) ──
  router.get("/api/live/nsg-detail", async (req: Request, res: Response) => {
    try {
      const resourceId = queryArmResourceId(req, env, "resourceId", true);
      const nsg = await fetchNsgInfo(env, req.auth?.bearerToken, resourceId);
      res.json(
        nsg ?? {
          name: resourceId.split("/").pop() ?? "nsg",
          resourceId,
          effectiveRules: mockNsgRules(),
          note: "mock",
        },
      );
    } catch (e: unknown) {
      sendError(res, e, "nsg_detail_error", "live-diagram");
    }
  });

  // ── Backend Pool Detail (LB / Application Gateway, 60s cached) ──
  router.get("/api/live/backend-pool", async (req: Request, res: Response) => {
    try {
      const resourceId = queryArmResourceId(req, env, "resourceId", true);
      const resourceKind = queryString(req, "resourceKind") ?? "lb";
      res.json({ pools: await fetchBackendPoolInfo(env, req.auth?.bearerToken, resourceId, resourceKind) });
    } catch (e: unknown) {
      sendError(res, e, "backend_pool_error", "live-diagram");
    }
  });

  // ── AKS Plane Detail (접속면 / 실행면 / 노출면, 60s cached) ──
  router.get("/api/live/aks-plane", async (req: Request, res: Response) => {
    try {
      const resourceId = queryArmResourceId(req, env, "resourceId", true);
      res.json(await fetchAksPlaneDetail(env, req.auth?.bearerToken, resourceId));
    } catch (e: unknown) {
      sendError(res, e, "aks_plane_error", "live-diagram");
    }
  });

  // ── VMSS Instances (for AKS nodepool VMSS, 60s cached) ──
  router.get("/api/live/vmss-instances", async (req: Request, res: Response) => {
    try {
      const resourceId = queryArmResourceId(req, env, "resourceId", true);
      const aksRaw = queryString(req, "aksClusterId");
      const aksClusterId = aksRaw ? assertArmResourceId(env, aksRaw, "aksClusterId", true) : undefined;
      res.json({ instances: await fetchVmssInstances(env, req.auth?.bearerToken, resourceId, aksClusterId) });
    } catch (e: unknown) {
      sendError(res, e, "vmss_instances_error", "live-diagram");
    }
  });

  // ── Data source status ──
  router.get("/api/live/status", (_req: Request, res: Response) => {
    res.json({
      azureEnabled: env.AZURE_LIVE_DIAGRAM_ENABLED,
      appInsightsConfigured: !!env.AZURE_APP_INSIGHTS_APP_ID,
      oboConfigured: !!(env.AZURE_AD_TENANT_ID && env.AZURE_AD_CLIENT_ID && env.AZURE_AD_CLIENT_SECRET),
      trafficSources: {
        trafficAnalytics: env.AZURE_TRAFFIC_ANALYTICS_ENABLED && !!env.AZURE_LOG_ANALYTICS_WORKSPACE_ID,
        nsgFlowLogs: !!env.AZURE_NSG_FLOW_LOG_STORAGE_ACCOUNT,
        appInsightsDependencies: !!env.AZURE_APP_INSIGHTS_APP_ID,
        connectionMonitor: env.AZURE_CONNECTION_MONITOR_ENABLED,
      },
      cacheTtl: {
        metrics: env.AZURE_LIVE_METRICS_CACHE_TTL_MS,
        alerts: env.AZURE_MONITOR_ALERTS_CACHE_TTL_MS,
        appInsights: env.AZURE_APP_INSIGHTS_CACHE_TTL_MS,
        trafficAnalytics: env.AZURE_TRAFFIC_ANALYTICS_CACHE_TTL_MS,
        nsgFlowLogs: env.AZURE_NSG_FLOW_LOG_CACHE_TTL_MS,
        connectionMonitor: env.AZURE_CONNECTION_MONITOR_CACHE_TTL_MS,
      },
    });
  });
}

/** Check if the snapshot has any resolved metrics (not all zeros/empty) */
function hasRealData(snapshot: LiveDiagramSnapshot): boolean {
  return (snapshot.topology?.resolvedBindings ?? 0) > 0;
}

/** Tag a snapshot with its data source for frontend debugging */
function withSource<T extends object>(
  data: T,
  source: "azure" | "mock",
  error?: string,
): T & { _source: string; _error?: string } {
  return { ...data, _source: source, ...(error ? { _error: error } : {}) };
}

