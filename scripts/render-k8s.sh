#!/usr/bin/env bash
# Renders the Helm chart (deploy/helm/aud-dashboard, placeholders from values.yaml) into the plain reference
# manifest deploy/kubernetes/aud-dashboard.yaml — for readers and kubectl/kustomize users. Run after changing the
# chart; apps/api/test/deployChart.test.ts fails when the two differ (when helm is installed).
set -euo pipefail
cd "$(dirname "$0")/.."
out=deploy/kubernetes/aud-dashboard.yaml
{
  echo "# GENERATED by scripts/render-k8s.sh from deploy/helm/aud-dashboard (values.yaml placeholders) — do not edit."
  echo "# Optional pieces (HTTPRoute, AGC HealthCheckPolicy, CiliumNetworkPolicy) are rendered on: see values.yaml."
  helm template aud-dashboard deploy/helm/aud-dashboard --namespace aud-dashboard \
    --set gateway.enabled=true --set healthCheckPolicy.enabled=true --set networkPolicy.enabled=true \
    | grep -v '^# Source: ' | tr -d '\r'
} > "$out"
echo "wrote $out"
